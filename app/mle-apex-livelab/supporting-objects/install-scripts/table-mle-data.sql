  CREATE TABLE "MLE_DATA" 
   (	"ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY  NOT NULL ENABLE, 
	"POST_COMMENT" VARCHAR2(4000 CHAR), 
	"FILE_BLOB" BLOB, 
	"FILE_MIME" VARCHAR2(255 CHAR), 
	"FILE_NAME" VARCHAR2(255 CHAR), 
	"LAT" NUMBER, 
	"LON" NUMBER, 
	"CREATED" DATE NOT NULL ENABLE, 
	"CREATED_BY" VARCHAR2(255 CHAR) NOT NULL ENABLE, 
	"UPDATED" DATE, 
	"UPDATED_BY" VARCHAR2(255 CHAR), 
	"EXIF_DATA" JSON, 
	"THUMBNAIL" BLOB, 
	"IMAGE_DIMENSION" VARCHAR2(4000), 
	 CONSTRAINT "MLE_DATA_ID_PK" PRIMARY KEY ("ID")
  USING INDEX  ENABLE
   ) ;


  CREATE OR REPLACE EDITIONABLE TRIGGER "MLE_DATA_BIU" 
before insert or update on MLE_DATA
for each row
begin
    if inserting then
        :new.created := coalesce(:new.created, sysdate);
        :new.created_by := coalesce(
            :new.created_by,
            sys_context('APEX$SESSION', 'APP_USER'),
            user
        );
    end if;

    :new.updated := sysdate;
    :new.updated_by := coalesce(
        sys_context('APEX$SESSION', 'APP_USER'),
        user
    );
end;
/
