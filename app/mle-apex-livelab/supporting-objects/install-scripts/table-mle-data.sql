  CREATE TABLE if not exists "MLE_DATA" 
   (	"ID" NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY, 
	"POST_COMMENT" VARCHAR2(4000 CHAR), 
	"FILE_BLOB" BLOB, 
	"THUMBNAIL" BLOB,
	"FILE_MIME" VARCHAR2(255 CHAR), 
	"FILE_NAME" VARCHAR2(255 CHAR), 
	"LAT" NUMBER, 
	"LON" NUMBER, 
	"CREATED" DATE NOT NULL, 
	"CREATED_BY" VARCHAR2(255 CHAR) NOT NULL, 
	"UPDATED" DATE, 
	"UPDATED_BY" VARCHAR2(255 CHAR),
    "EXIF_DATA" JSON,
    CONSTRAINT "MLE_DATA_ID_PK" PRIMARY KEY ("ID")
   ) ;

-- CREATE TABLE IF NOT EXISTS does not change an existing table.
declare
    l_count integer;
begin
    select count(*) into l_count from user_tab_columns
    where table_name = 'MLE_DATA' and column_name = 'THUMBNAIL';
    if l_count = 0 then
        execute immediate 'alter table mle_data add (thumbnail blob)';
    end if;
end;
/

  CREATE OR REPLACE EDITIONABLE TRIGGER "MLE_DATA_BIU" 
before insert or update on MLE_DATA
for each row
begin
    if inserting then
        :new.created := coalesce(:new.created, sysdate);
        :new.created_by := coalesce(
            :new.created_by,
            sys_context('APEX$SESSION', 'APP_USER'),
            user
        );
    end if;

    :new.updated := sysdate;
    :new.updated_by := coalesce(
        sys_context('APEX$SESSION', 'APP_USER'),
        user
    );
end;
/
ALTER TRIGGER "MLE_DATA_BIU" ENABLE;

