create table if not exists mle_data_ela (
    id number generated by default on null as identity primary key,
    mle_data_id number not null,
    status varchar2(10 char) default 'PENDING' not null,
    ela_image blob,
    metadata json,
    error_message varchar2(1000 char),
    constraint mle_data_ela_photo_uk unique (mle_data_id),
    constraint mle_data_ela_photo_fk foreign key (mle_data_id)
        references mle_data (id) on delete cascade,
    constraint mle_data_ela_status_ck check (status in ('PENDING', 'READY', 'FAILED'))
);
